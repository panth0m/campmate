// ── 언어 감지 및 적용 ──────────────────────────────────────

const I18N = (() => {
  const SUPPORTED = ['en', 'ko', 'zh', 'ja'];
  const STORAGE_KEY = 'campmate-lang';

  function detect() {
    // 1. 저장된 선택 우선
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
    // 2. 브라우저 언어 자동 감지
    const langs = navigator.languages || [navigator.language || 'en'];
    for (const l of langs) {
      const code = l.toLowerCase().slice(0, 2);
      if (SUPPORTED.includes(code)) return code;
    }
    return 'en';
  }

  function get(key) {
    const lang = detect();
    return (CAMPMATE_I18N[lang] && CAMPMATE_I18N[lang][key]) || CAMPMATE_I18N['en'][key] || key;
  }

  function set(lang) {
    if (!SUPPORTED.includes(lang)) return;
    localStorage.setItem(STORAGE_KEY, lang);
    location.reload();
  }

  function current() { return detect(); }

  // DOM에 data-i18n 속성 기반 자동 번역
  function applyDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      const val = get(key);
      if (el.tagName === 'INPUT') el.placeholder = val;
      else el.textContent = val;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = get(el.dataset.i18nPlaceholder);
    });
  }

  return { detect, get, set, current, apply: applyDOM, SUPPORTED };
})();

// ── 언어 선택 UI 생성 ──────────────────────────────────────

function buildLangSwitcher() {
  const FLAGS = { en: '🇦🇺', ko: '🇰🇷', zh: '🇨🇳', ja: '🇯🇵' };
  const NAMES = { en: 'EN', ko: '한국어', zh: '中文', ja: '日本語' };
  const current = I18N.current();

  const wrap = document.createElement('div');
  wrap.className = 'lang-switcher';
  wrap.innerHTML = `
    <button class="lang-btn" id="lang-btn" aria-label="Language">
      <span>${FLAGS[current]}</span>
      <span>${NAMES[current]}</span>
      <svg width="12" height="12" viewBox="0 0 12 12" fill="currentColor"><path d="M2 4l4 4 4-4"/></svg>
    </button>
    <div class="lang-dropdown" id="lang-dropdown">
      ${I18N.SUPPORTED.map(lang => `
        <button class="lang-option ${lang === current ? 'active' : ''}" data-lang="${lang}">
          <span>${FLAGS[lang]}</span> ${NAMES[lang]}
        </button>`).join('')}
    </div>`;

  // 토글
  wrap.querySelector('#lang-btn').addEventListener('click', e => {
    e.stopPropagation();
    wrap.querySelector('#lang-dropdown').classList.toggle('open');
  });
  document.addEventListener('click', () => {
    wrap.querySelector('#lang-dropdown').classList.remove('open');
  });
  wrap.querySelectorAll('.lang-option').forEach(btn => {
    btn.addEventListener('click', () => I18N.set(btn.dataset.lang));
  });

  return wrap;
}

// ── 네비게이션에 언어 선택기 삽입 ─────────────────────────

function setupI18N() {
  // DOM 번역 적용
  I18N.apply();

  // 언어 선택기를 nav에 삽입
  const nav = document.querySelector('.container.nav') || document.querySelector('.nav');
  if (nav) {
    const switcher = buildLangSwitcher();
    nav.appendChild(switcher);
  }

  // nav 검색창 placeholder 번역
  const searchInput = document.querySelector('[data-search-form] input, .nav-search input');
  if (searchInput) searchInput.placeholder = I18N.get('nav_search_placeholder');

  // 탭바 번역
  const tabLabels = {
    'index.html': 'tab_home',
    'categories.html': 'tab_browse',
    'search.html': 'tab_search',
    'popular.html': 'tab_popular',
    'guides.html': 'tab_guides',
  };
  document.querySelectorAll('.mob-tab').forEach(tab => {
    const href = tab.getAttribute('href') || '';
    const page = href.split('/').pop();
    const key = tabLabels[page];
    if (key) {
      const textNode = [...tab.childNodes].find(n => n.nodeType === 3 && n.textContent.trim());
      if (textNode) textNode.textContent = '\n      ' + I18N.get(key) + '\n    ';
    }
  });
}

// 페이지 로드 후 자동 실행
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', setupI18N);
} else {
  setupI18N();
}
